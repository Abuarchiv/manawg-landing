// Run with: pnpm test (node test runner, no framework)
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

const pages = {
	'en/privacy': 'src/app/(en)/en/privacy/page.tsx',
	'de/datenschutz': 'src/app/(de)/datenschutz/page.tsx',
};

const text = (file: string) => readFileSync(file, 'utf8').replace(/\s+/g, ' ');

test('both privacy texts list invite analytics and share methods', () => {
	for (const [name, file] of Object.entries(pages)) {
		const body = text(file).match(/4f\..*?<\/section>/)?.[0] ?? '';
		for (const event of [
			'invite_card_shown',
			'invite_card_shared',
			'invite_card_dismissed',
			'invite_step_shown',
			'invite_step_shared',
			'invite_step_skipped',
		])
			assert.ok(body.includes(event), `${name}: ${event}`);
		assert.match(body, /invite_card_shared.{0,100}method.{0,100}share.{0,20}copy/, name);
		assert.match(
			body,
			/invite_step_shared.{0,100}method.{0,100}share.{0,20}copy.{0,20}whatsapp/,
			name,
		);
	}
});

test('the privacy texts do not name jsDelivr, because the app serves the OCR files itself', () => {
	for (const [name, file] of Object.entries(pages)) {
		assert.doesNotMatch(text(file), /jsdelivr/i, name);
	}
});

test('the privacy texts name the password check and the IndexedDB storage', () => {
	for (const [name, file] of Object.entries(pages)) {
		assert.match(text(file), /Have I Been Pwned/, name);
		assert.match(text(file), /IndexedDB/, name);
	}
});

test('the privacy texts do not limit browser storage to flat assignments and name drafts', () => {
	assert.doesNotMatch(
		text(pages['de/datenschutz']),
		/WG-Zuordnungen und Namensentwürfe im lokalen/,
	);
	assert.doesNotMatch(text(pages['en/privacy']), /flat assignments and name drafts may be held/);
});

test('the privacy texts name the stored User-Agent in the push notification section', () => {
	const push = {
		'en/privacy': /push address generated by the browser.{0,200}/,
		'de/datenschutz': /Push-Adresse.{0,200}/,
	};
	for (const [name, file] of Object.entries(pages)) {
		assert.match(text(file).match(push[name as keyof typeof push])?.[0] ?? '', /User-Agent/, name);
	}
});

test('the privacy texts describe a connected AI assistant and how to disconnect it', () => {
	const section = {
		'en/privacy': /4h\. Connected AI assistants.*?<\/section>/,
		'de/datenschutz': /4h\. Verbundene KI-Assistenten.*?<\/section>/,
	};
	const revoke = {
		'en/privacy': /Settings.{0,40}Access/,
		'de/datenschutz': /Einstellungen.{0,40}Zugang/,
	};
	for (const [name, file] of Object.entries(pages)) {
		const body = text(file).match(section[name as keyof typeof section])?.[0] ?? '';
		assert.match(body, /MCP/, name);
		assert.match(body, /OAuth/, name);
		assert.match(body, revoke[name as keyof typeof revoke], name);
	}
});
